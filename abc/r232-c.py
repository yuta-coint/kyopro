"""足すモードから引くモードに好きな回数切り替えられるわけで、
高々2回適切なタイミングで行えば十分。
1を加える操作をk回行うのだが、
1回negateすることで、絶対値を逆にしたうえで、+kから-kまでを2刻みに選択できる。
2回negateすることで、絶対値を保ったうえで、+kから-kまでを2刻みに選択できる。
まず偶奇の問題を何とかする必要があって、基本的に偶奇はkの偶奇のみによって決まる。
逆に、偶奇の問題だけ何とかなっていれば、実現はできる。
割り当てがきまれば、
「差がkなら0点」「和がk以下なら1点」「差がk以下なら2点」になる。
差をk以下にするだけなら、小さい順に並べれば最小のkを割り出せるが、
和が認められているのがあまりに面倒。
符号と割り当てを決めれば「kを最小化する」「各kに合わせる」の中で最善を採択すれば、O(N)で求まりそう。
というか割り当てが決まった時点で、「kがいくつの時0になるか」「kがいくつ以上で1になるか」「kがいくつ以上で2になるか」はわかるので、
これは、O(N^2)で全計算ができるので、あとはマッチングゲーになるのか。
候補になるkも同じくらいのオーダーでいい。よって、O(N^6)くらいで解けたことになる。
「k = |B - A|なら0」「k >= |A + B|なら1」「k >= |B - A|なら2」
"""

